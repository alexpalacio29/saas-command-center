export function generateComprehensiveStageChecklists(
  productId: string,
  completedUpToStep: number = 3
): StageChecklistItem[] {
  const result: StageChecklistItem[] = [];

  CANONICAL_STAGE_DEFINITIONS.forEach((stageDef) => {
    stageDef.items.forEach((item, idx) => {
      let isCompleted = false;
      if (stageDef.step < completedUpToStep) {
        isCompleted = true;
      } else if (stageDef.step === completedUpToStep) {
        isCompleted = idx < Math.ceil(stageDef.items.length * 0.65);
      } else {
        isCompleted = false;
      }

      let notes: string | undefined = undefined;
      if (productId === 'prod-edugest' && item.id === 'val-1') {
        notes = 'Entrevistas con 8 directores de colegios en Santo Domingo y Santiago. Validación positiva del módulo de calificaciones y cobros.';
      } else if (productId === 'prod-edugest' && item.id === 'mvp-1') {
        notes = 'Arquitectura multi-tenant lista con aislamiento de datos por centro educativo.';
      } else if (productId === 'prod-gestify' && item.id === 'val-1') {
        notes = 'Reuniones en ferreterías de Santo Domingo. Problema crítico validado: descuadre de inventario y facturación rápida.';
      }

      result.push({
        id: `${productId}-${item.id}`,
        stage: stageDef.id,
        label: item.label,
        completed: isCompleted,
        requiredForNextStage: true,
        notes,
      });
    });
  });

  return result;
}

function generateChecklistForStage(stage: ProductStage, completedCount: number = 0): StageChecklistItem[] {
  const templates = DEFAULT_STAGE_CHECKLIST_TEMPLATES[stage] || [];
  return templates.map((label, idx) => ({
    id: `chk-${stage}-${idx}`,
    stage,
    label,
    completed: idx < completedCount,
    requiredForNextStage: true,
  }));
}

